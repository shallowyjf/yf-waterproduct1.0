"""Generate neutral surface overrides. Semantic map and status colors stay unchanged."""
from pathlib import Path
import re, colorsys
root=Path(__file__).resolve().parents[1]
files=['base','layout','components','patterns','gis','utilities','product','topology-editor','unified-maps','device-binding','operations','hydraulics']
output=['/* Generated by tools/build-dark-theme.py; regenerate after adding hardcoded neutral colors. */']
literal=re.compile(r'#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|\bwhite\b|\bblack\b')
def convert(match,prop,selector):
    raw=match.group(0);h={'white':'ffffff','black':'000000'}.get(raw,raw.lstrip('#'))
    if len(h)==3:h=''.join(c*2 for c in h)
    r,g,b=[int(h[i:i+2],16)/255 for i in (0,2,4)]
    hue,light,sat=colorsys.rgb_to_hls(r,g,b);neutral=max(r,g,b)-min(r,g,b)<.32 or sat<.56
    replacement=None
    if prop in ['color','caret-color'] and light<.73 and neutral:replacement='#d5dfec' if light<.4 else '#a4b3c7'
    elif prop.startswith('background') and light>.7:
        if 'map' in selector and not any(t in selector for t in ['panel','button','toolbar','legend','tools','list','detail','context','record','select','header','timeline']):replacement='#111e2c'
        else:replacement='#192534' if light>.97 else '#142131'
        if not neutral:replacement='#20374c'
    elif prop.startswith('border') and (light>.5 or neutral):replacement='#344558'
    if not replacement:return raw
    return replacement+(h[6:] if len(h)==8 else '')
for file in files:
    text=re.sub(r'/\*.*?\*/','',(root/'styles'/f'{file}.css').read_text(encoding='utf-8'),flags=re.S)
    for rule in re.finditer(r'([^{}]+)\{([^{}]*)\}',text):
        selector=rule[1].strip();decl=[]
        if selector.startswith('@') or selector==':root':continue
        for part in rule[2].split(';'):
            if ':' not in part:continue
            prop,value=part.split(':',1);prop=prop.strip();value=value.strip()
            if prop not in ['color','caret-color','background','background-color','background-image','border','border-color','border-top','border-bottom','border-left','border-right']:continue
            mapped=literal.sub(lambda m:convert(m,prop,selector),value)
            if mapped!=value:decl.append(f'{prop}:{mapped}')
        if decl:
            selector=', '.join(':root[data-theme="dark"] '+s.strip() for s in selector.split(','))
            output.append(selector+'{'+ ';'.join(decl)+'}')
(root/'styles'/'dark-generated.css').write_text('\n'.join(output)+'\n',encoding='utf-8')
print(f'Generated {len(output)-1} dark surface rules')
